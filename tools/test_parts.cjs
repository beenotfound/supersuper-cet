const PW = 'C:/Users/黄枫/Documents/deepseek-harness/default-workspace/mc_history/skills/garden-skills-main/skills/motion-showreel/scripts/node_modules/playwright';
const { chromium } = require(PW);
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { const t=m.text(); if (m.type()==='error' && !t.includes('cloudflareinsights') && !t.includes('CORS') && !t.includes('ERR_FAILED')) errors.push(t); });
  await page.goto('http://127.0.0.1:8790/#/listening/cet6-2024-12-01', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1200);
  const players = await page.locator('audio').count();
  const labels = await page.locator('.v-listening').innerText();
  const srcs = await page.locator('audio').evaluateAll(as => as.map(a => a.currentSrc.split('/').pop()));
  await page.screenshot({ path: 'shots/listening-parts.png' });
  await page.goto('http://127.0.0.1:8790/#/listening/cet4-2015-12-03', { waitUntil: 'networkidle' });
  await page.waitForTimeout(900);
  const normalPlayers = await page.locator('audio').count();
  console.log(JSON.stringify({ errors, players, srcs, normalPlayers, labels: labels.slice(0,160) }, null, 2));
  await browser.close();
})();
