const PW = 'C:/Users/黄枫/Documents/deepseek-harness/default-workspace/mc_history/skills/garden-skills-main/skills/motion-showreel/scripts/node_modules/playwright';
const { chromium } = require(PW);
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const posts = [];
  page.on('response', r => { if (r.url().endsWith('/api/e')) posts.push(r.status()); });
  await page.goto('https://cet-prep-6ee.pages.dev/#/today', { waitUntil: 'networkidle' });
  await page.evaluate(() => localStorage.clear());
  await page.reload({ waitUntil: 'networkidle' });
  await page.waitForTimeout(800);
  await page.goto('https://cet-prep-6ee.pages.dev/#/onboarding', { waitUntil: 'networkidle' });
  await page.waitForTimeout(500);
  const cal = page.getByRole('button', { name: /开始词汇量校准/ }).first();
  if (await cal.count()) await cal.click({ force: true });
  await page.waitForTimeout(600);
  await page.goto('https://cet-prep-6ee.pages.dev/#/listening/cet4-2015-12-03', { waitUntil: 'networkidle' });
  await page.waitForTimeout(800);
  const start = page.getByRole('button', { name: /开始练习/ }).first();
  if (await start.count()) await start.click({ force: true });
  await page.waitForTimeout(1200);
  await page.goto('https://cet-prep-6ee.pages.dev/#/me', { waitUntil: 'networkidle' });
  await page.waitForTimeout(800);
  const privacy = await page.locator('text=匿名统计').count();
  await page.waitForTimeout(1500);
  console.log(JSON.stringify({ posts, privacy }, null, 2));
  await browser.close();
})();
