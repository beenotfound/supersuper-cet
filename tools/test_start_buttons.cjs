const PW='C:/Users/黄枫/Documents/deepseek-harness/default-workspace/mc_history/skills/garden-skills-main/skills/motion-showreel/scripts/node_modules/playwright';
const {chromium}=require(PW);
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const ctx=await browser.newContext({viewport:{width:1280,height:900},serviceWorkers:'block'});
 const page=await ctx.newPage(); const errors=[]; let failures=0;
 const check=(name,ok,detail='')=>{ console.log(`${ok?'PASS':'FAIL'}  ${name}${detail?'  '+detail:''}`); if(!ok) failures++; };
 page.on('pageerror',e=>errors.push('PAGEERROR '+e.message));
 page.on('console',m=>{const t=m.text(); if(m.type()==='error' && !t.includes('ERR_FAILED') && !t.includes('501') && !t.includes('cloudflareinsights')) errors.push('CONSOLE '+t);});
 const base='http://127.0.0.1:8790/';
 await page.goto(base+'#/today',{waitUntil:'networkidle'}); await page.waitForTimeout(600);
 await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('cetcollage.v1')||'{}'); s.profile=s.profile||{}; s.profile.onboarded=true; s.profile.level='cet6'; s.theta=0; s.stats=s.stats||{streak:0}; localStorage.setItem('cetcollage.v1',JSON.stringify(s));});
 await page.reload({waitUntil:'networkidle'}); await page.waitForTimeout(900);
 const studyBtn=page.getByRole('button',{name:/开始学习/}).first();
 check('今日开始学习按钮存在', (await studyBtn.count())===1);
 if(await studyBtn.count()) await studyBtn.click({force:true});
 await page.waitForTimeout(600);
 check('今日开始学习进入学习页', (await page.locator('.v-study').count())>0 || (await page.locator('.v-study__word, .v-study input, .v-study textarea').count())>0);
 await page.goto(base+'#/listening',{waitUntil:'networkidle'}); await page.waitForTimeout(900);
 const listenBtn=page.getByRole('button',{name:'开始练习'}).first();
 check('听力开始练习按钮存在', (await listenBtn.count())===1);
 if(await listenBtn.count()) await listenBtn.click({force:true});
 await page.waitForTimeout(600);
 check('听力开始练习进入答题', (await page.locator('audio, .v-exam__option, .c-audio, .v-listening__question').count())>0);
 await page.goto(base+'#/exam',{waitUntil:'networkidle'}); await page.waitForTimeout(900);
 const tile=page.locator('.v-exam__tile',{hasText:'选词填空'}).first();
 const practiceBtn=tile.getByRole('button',{name:'开始'}).first();
 check('专项练习开始按钮存在', (await practiceBtn.count())===1);
 if(await practiceBtn.count()) await practiceBtn.click({force:true});
 await page.waitForTimeout(600);
 check('专项练习进入答题', (await page.locator('.v-exam select, .v-exam__option, .v-exam textarea').count())>0);
 check('无页面 JS 错误', errors.length===0, errors.join(' | '));
 console.log(failures?`\n${failures} failed`:'\nALL PASS');
 await browser.close(); process.exit(failures?1:0);
})();
