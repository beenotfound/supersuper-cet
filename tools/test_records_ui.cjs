const PW = 'C:/Users/黄枫/Documents/deepseek-harness/default-workspace/mc_history/skills/garden-skills-main/skills/motion-showreel/scripts/node_modules/playwright';
const { chromium } = require(PW);
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
  page.on('console', m => { const t=m.text(); if (m.type()==='error' && !t.includes('501') && !t.includes('ERR_FAILED') && !t.includes('cloudflareinsights')) errors.push('CONSOLE ' + t); });
  await page.goto('http://127.0.0.1:8790/#/exam', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1000);
  const now = Date.now();
  const examAttempt = { id:'att-rec', paperId:'paper-01', paperTitle:'六级模拟卷 1', level:'cet6', startedAt:now-300000, finishedAt:now, session:{correct:3,total:15,pending:0,byType:{}}, items:[{itemId:'x',type:'cloze',correct:3,total:10,detail:[],response:[],elapsedMs:600000}], writing:null, translation:null, listening:null };
  await page.evaluate((a) => {
    const s = JSON.parse(localStorage.getItem('cetcollage.v1') || '{}');
    s.examAttempts = [a];
    s.practiceAttempts = [{ id:'prac-1', type:'cloze', title:'选词填空', startedAt:Date.now()-60000, finishedAt:Date.now(), items:[{itemId:'cloze-001',type:'cloze',correct:7,total:10,detail:[],response:[],elapsedMs:300000}] }];
    s.wrongBook = [{ key:'cloze-001:0', itemId:'cloze-001', qIndex:0, type:'cloze', prompt:'第 1 空', mine:'wrong', correct:'memorable', explain:'测试解析', count:2, lastAt:Date.now() }];
    s.practiceSeen = { 'cloze-001': { count:1, wrong:1, lastAt:Date.now() } };
    localStorage.setItem('cetcollage.v1', JSON.stringify(s));
  }, examAttempt);
  await page.reload({ waitUntil:'networkidle' });
  await page.waitForTimeout(1200);
  const expand = page.getByRole('button', { name: /显示全部/ }).first();
  if (await expand.count()) await expand.click({ force: true });
  await page.waitForTimeout(400);
  const homeText = await page.locator('#app').innerText();
  const subtitleAtTop = homeText.indexOf('词汇题') < homeText.indexOf('最近模考');
  const status = homeText.includes('上次') && homeText.includes('看上次报告');
  const reportBtn = page.getByRole('button', { name: '看上次报告' }).first();
  const hasReportBtn = await reportBtn.count();
  await page.goto('http://127.0.0.1:8790/#/records', { waitUntil:'networkidle' });
  await page.waitForTimeout(900);
  const recText = await page.locator('#app').innerText();
  const hasTabs = recText.includes('模考记录') && recText.includes('专项记录') && recText.includes('错题本');
  const hasExamRow = recText.includes('六级模拟卷 1');
  const examRow = page.locator('.v-records__row', { hasText: '六级模拟卷 1' }).first();
  if (await examRow.count()) await examRow.click({ force: true });
  await page.waitForTimeout(700);
  const examRowReport = page.url().includes('#/report/att-rec') && (await page.locator('text=模考报告').count()) > 0;
  await page.goto('http://127.0.0.1:8790/#/records', { waitUntil:'networkidle' });
  await page.waitForTimeout(600);
  await page.getByRole('button', { name: '专项记录' }).click({ force: true });
  await page.waitForTimeout(300);
  const practiceText = await page.locator('#app').innerText();
  const hasPractice = practiceText.includes('选词填空') && practiceText.includes('正确');
  await page.getByRole('button', { name: '错题本' }).click({ force: true });
  await page.waitForTimeout(300);
  const wrongText = await page.locator('#app').innerText();
  const hasWrong = wrongText.includes('测试解析') && wrongText.includes('重做这些错题');
  const redo = page.getByRole('button', { name: '重做这些错题' }).first();
  const hasRedo = await redo.count();
  if (hasRedo) await redo.click({ force: true });
  await page.waitForTimeout(900);
  const started = page.url().includes('#/exam') && (await page.locator('.v-exam').count()) > 0;
  await page.goto('http://127.0.0.1:8790/#/me', { waitUntil:'networkidle' });
  await page.waitForTimeout(700);
  const lastText = await page.locator('.v-me > *').last().innerText().catch(() => '');
  const privacyBottom = lastText.includes('匿名统计');
  console.log(JSON.stringify({ errors, subtitleAtTop, privacyBottom, status, hasReportBtn, hasTabs, hasExamRow, examRowReport, hasPractice, hasWrong, hasRedo, started, url: page.url() }, null, 2));
  await browser.close();
})();
